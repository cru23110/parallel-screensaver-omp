// Fuente de mapa de bits de 5x7 incluida en el programa.
//
// Se dibuja el reloj y el HUD con esto en vez de con SDL2_ttf para no arrastrar
// una libreria mas (ni un archivo .ttf que habria que distribuir) por dos
// lineas de texto. Cada glifo son 7 bytes; de cada byte se usan los 5 bits
// bajos, donde el bit 4 es la columna de la izquierda.
//
// Ejemplo, el glifo del 7:
//     0x1F -> 11111
//     0x01 -> ....1
//     0x02 -> ...1.
//     0x04 -> ..1..
//     0x08 -> .1...
//     0x08 -> .1...
//     0x08 -> .1...

#include <cctype>
#include <cstring>
#include <vector>

#include "text.hpp"

namespace {

constexpr int kGlyphWidth = 5;   // Columnas de un glifo.
constexpr int kGlyphHeight = 7;  // Filas de un glifo.
constexpr int kGlyphSpacing = 1; // Columnas en blanco entre glifo y glifo.

// Un glifo es una fila de la tabla: 7 filas de 5 pixeles.
using Glyph = unsigned char[kGlyphHeight];

const Glyph kDigits[10] = {
    {0x0E, 0x11, 0x13, 0x15, 0x19, 0x11, 0x0E}, // 0
    {0x04, 0x0C, 0x04, 0x04, 0x04, 0x04, 0x0E}, // 1
    {0x0E, 0x11, 0x01, 0x02, 0x04, 0x08, 0x1F}, // 2
    {0x1F, 0x02, 0x04, 0x02, 0x01, 0x11, 0x0E}, // 3
    {0x02, 0x06, 0x0A, 0x12, 0x1F, 0x02, 0x02}, // 4
    {0x1F, 0x10, 0x1E, 0x01, 0x01, 0x11, 0x0E}, // 5
    {0x06, 0x08, 0x10, 0x1E, 0x11, 0x11, 0x0E}, // 6
    {0x1F, 0x01, 0x02, 0x04, 0x08, 0x08, 0x08}, // 7
    {0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E}, // 8
    {0x0E, 0x11, 0x11, 0x0F, 0x01, 0x02, 0x0C}, // 9
};

const Glyph kLetters[26] = {
    {0x0E, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11}, // A
    {0x1E, 0x11, 0x11, 0x1E, 0x11, 0x11, 0x1E}, // B
    {0x0E, 0x11, 0x10, 0x10, 0x10, 0x11, 0x0E}, // C
    {0x1E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1E}, // D
    {0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x1F}, // E
    {0x1F, 0x10, 0x10, 0x1E, 0x10, 0x10, 0x10}, // F
    {0x0E, 0x11, 0x10, 0x17, 0x11, 0x11, 0x0F}, // G
    {0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11}, // H
    {0x0E, 0x04, 0x04, 0x04, 0x04, 0x04, 0x0E}, // I
    {0x07, 0x02, 0x02, 0x02, 0x02, 0x12, 0x0C}, // J
    {0x11, 0x12, 0x14, 0x18, 0x14, 0x12, 0x11}, // K
    {0x10, 0x10, 0x10, 0x10, 0x10, 0x10, 0x1F}, // L
    {0x11, 0x1B, 0x15, 0x15, 0x11, 0x11, 0x11}, // M
    {0x11, 0x19, 0x19, 0x15, 0x13, 0x13, 0x11}, // N
    {0x0E, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E}, // O
    {0x1E, 0x11, 0x11, 0x1E, 0x10, 0x10, 0x10}, // P
    {0x0E, 0x11, 0x11, 0x11, 0x15, 0x12, 0x0D}, // Q
    {0x1E, 0x11, 0x11, 0x1E, 0x14, 0x12, 0x11}, // R
    {0x0F, 0x10, 0x10, 0x0E, 0x01, 0x01, 0x1E}, // S
    {0x1F, 0x04, 0x04, 0x04, 0x04, 0x04, 0x04}, // T
    {0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E}, // U
    {0x11, 0x11, 0x11, 0x11, 0x11, 0x0A, 0x04}, // V
    {0x11, 0x11, 0x11, 0x15, 0x15, 0x1B, 0x11}, // W
    {0x11, 0x11, 0x0A, 0x04, 0x0A, 0x11, 0x11}, // X
    {0x11, 0x11, 0x0A, 0x04, 0x04, 0x04, 0x04}, // Y
    {0x1F, 0x01, 0x02, 0x04, 0x08, 0x10, 0x1F}, // Z
};

const Glyph kBlank      = {0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00};
const Glyph kColon      = {0x00, 0x0C, 0x0C, 0x00, 0x0C, 0x0C, 0x00};
const Glyph kPeriod     = {0x00, 0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C};
const Glyph kComma      = {0x00, 0x00, 0x00, 0x00, 0x0C, 0x0C, 0x08};
const Glyph kHyphen     = {0x00, 0x00, 0x00, 0x1F, 0x00, 0x00, 0x00};
const Glyph kEquals     = {0x00, 0x00, 0x1F, 0x00, 0x1F, 0x00, 0x00};
const Glyph kSlash      = {0x01, 0x02, 0x02, 0x04, 0x08, 0x08, 0x10};
const Glyph kPercent    = {0x11, 0x12, 0x02, 0x04, 0x08, 0x09, 0x11};
const Glyph kParenOpen  = {0x02, 0x04, 0x08, 0x08, 0x08, 0x04, 0x02};
const Glyph kParenClose = {0x08, 0x04, 0x02, 0x02, 0x02, 0x04, 0x08};

// Devuelve el glifo que corresponde a un caracter. Las minusculas se dibujan
// como mayusculas y lo que no este en la tabla sale en blanco, para que un
// texto inesperado nunca rompa el dibujo.
const unsigned char* glyphFor(char character) {
    const unsigned char c = static_cast<unsigned char>(std::toupper(static_cast<unsigned char>(character)));

    if (c >= '0' && c <= '9') return kDigits[c - '0'];
    if (c >= 'A' && c <= 'Z') return kLetters[c - 'A'];

    switch (c) {
        case ':': return kColon;
        case '.': return kPeriod;
        case ',': return kComma;
        case '-': return kHyphen;
        case '=': return kEquals;
        case '/': return kSlash;
        case '%': return kPercent;
        case '(': return kParenOpen;
        case ')': return kParenClose;
        default:  return kBlank;
    }
}

} // namespace

int textHeight(int scale) {
    return kGlyphHeight * scale;
}

int textWidth(const char* text, int scale) {
    const int length = static_cast<int>(std::strlen(text));
    if (length == 0) return 0;

    // Cada caracter ocupa su ancho mas un espacio, menos el ultimo, que no
    // lleva espacio despues.
    return length * (kGlyphWidth + kGlyphSpacing) * scale - kGlyphSpacing * scale;
}

void drawText(SDL_Renderer* renderer, const char* text, int x, int y, int scale, SDL_Color color) {
    // Todos los pixeles encendidos de la cadena se juntan en un solo lote y se
    // mandan de una sola vez, en vez de una llamada de dibujo por pixel.
    std::vector<SDL_Rect> pixels;
    pixels.reserve(std::strlen(text) * 16);

    int penX = x;
    for (const char* c = text; *c != '\0'; ++c) {
        const unsigned char* glyph = glyphFor(*c);

        for (int row = 0; row < kGlyphHeight; ++row) {
            const unsigned char bits = glyph[row];
            for (int column = 0; column < kGlyphWidth; ++column) {
                // El bit 4 es la columna de la izquierda, por eso se desplaza
                // desde kGlyphWidth - 1 hacia abajo.
                if ((bits >> (kGlyphWidth - 1 - column)) & 1) {
                    pixels.push_back(SDL_Rect{penX + column * scale, y + row * scale, scale, scale});
                }
            }
        }

        penX += (kGlyphWidth + kGlyphSpacing) * scale;
    }

    if (pixels.empty()) return;

    SDL_SetRenderDrawColor(renderer, color.r, color.g, color.b, color.a);
    SDL_RenderFillRects(renderer, pixels.data(), static_cast<int>(pixels.size()));
}
